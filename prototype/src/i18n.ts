export function getLanguage(): Language {
  return currentLanguage
}

export function setLanguage(language: Language): void {
  currentLanguage = language === 'en' ? 'en' : 'zh'
  document.documentElement.lang = currentLanguage === 'en' ? 'en' : 'zh-CN'
}

function interpolate(value: string, vars?: Record<string, string | number>): string {
  if (!vars) return value
  return value.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`))
}

export function t(text: string, vars?: Record<string, string | number>): string {
  if (currentLanguage === 'zh') return interpolate(text, vars)
  const exact = EN[text]
  if (exact) return interpolate(exact, vars)
  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(text)) return interpolate(text.replace(pattern, replacement), vars)
  }
  // Keep unknown strings in their source language rather than showing empty UI.
  return interpolate(text, vars)
}
